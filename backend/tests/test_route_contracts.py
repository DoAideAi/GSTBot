class TestEveryDecimalInAQueryStringIsBounded:
    """The same hole as the integers above, one type over.

    ``Decimal`` accepts more strings than a number line has points, and the two
    extras are the whole problem:

    *   ``Decimal("nan")`` and ``Decimal("inf")`` construct without raising.
        Only *arithmetic* on them raises, so a route that guards its parse with
        ``except InvalidOperation`` catches nothing and the failure surfaces
        wherever the value is first compared — a 500 several layers from the
        query string that caused it.
    *   ``Decimal("1E+999999999")`` constructs just as cheaply and is not a
        figure any money column could hold.

    A ``ge``/``le`` pair rejects all three at the boundary, before a service
    sees them, and turns a 500 into the 422 the caller earned. That is what
    ``/itc`` already did and what ``/filing/{return_type}/late-fee`` did not —
    it took the same figure as a ``str`` and parsed it by hand, which put it
    outside every declarative bound and outside this sweep's reach until it
    was spelled as a ``Decimal``.

    A negative bound matters as much as the huge one here. These parameters are
    money, ``turnover_tier`` reads the smallest matching band, and a negative
    turnover selected the *lowest* late-fee cap — a confidently wrong ceiling
    on a compliance figure, which is worse than an error.
    """

    def _decimal_params(self, route):
        """Every path or query parameter this route reads as a Decimal.

        The union is unwrapped, unlike the integer sweep above, because every
        one of these is optional: an omitted turnover is a real case with its
        own answer, so they are spelled ``Decimal | None`` and an identity test
        against ``Decimal`` matches none of them. That is not a hypothetical —
        it is how the first draft of this sweep passed while the bug it was
        written for was still live.
        """
        found = []
        for param in (*route.dependant.query_params, *route.dependant.path_params):
            annotation = param.field_info.annotation
            options = [a for a in get_args(annotation) if a is not type(None)]
            if len(options) == 1:
                annotation = options[0]
            if annotation is Decimal:
                found.append((param.name, param.field_info))
        return found

    def _bound(self, field_info, *names):
        for meta in getattr(field_info, "metadata", []) or []:
            for name in names:
                if getattr(meta, name, None) is not None:
                    return getattr(meta, name)
        return None

    def test_the_sweep_finds_the_parameters_it_is_checking(self):
        # A collector that finds nothing passes everything below. Named rather
        # than counted: these three are the money figures a caller can pass in
        # a query string today, and losing one silently would empty the sweep.
        found = {
            name
            for route in collect_api_routes(app)
            if hasattr(route, "dependant")
            for name, _ in self._decimal_params(route)
        }
        assert {"exempt_turnover", "total_turnover", "previous_year_turnover"} <= found, found

    def test_every_decimal_parameter_has_a_ceiling(self):
        offenders = []
        for route in collect_api_routes(app):
            if not hasattr(route, "dependant"):
                continue
            for name, field_info in self._decimal_params(route):
                if self._bound(field_info, "le", "lt") is None:
                    offenders.append(f"{route.path}:{name}")
        assert not offenders, (
            "these take a Decimal of any magnitude, so 'inf' and '1E+999999999' "
            f"reach a service — bound them with ``le=MONEY_MAX``: {offenders}"
        )

    def test_every_decimal_parameter_has_a_floor(self):
        offenders = []
        for route in collect_api_routes(app):
            if not hasattr(route, "dependant"):
                continue
            for name, field_info in self._decimal_params(route):
                if self._bound(field_info, "ge", "gt") is None:
                    offenders.append(f"{route.path}:{name}")
        assert not offenders, (
            "these accept a negative amount of money, which no caller means and "
            f"which selects the lowest cap tier rather than erroring: {offenders}"
        )

    # Every route/parameter pair the sweep above found, exercised over HTTP.
    # The sweep proves the bound is declared; these prove the declaration is
    # what a caller actually meets, which is the half a metadata walk cannot
    # see — a bound on the wrong parameter still passes the sweep.
    DECIMAL_QUERIES = [
        ("/api/v1/itc", "exempt_turnover"),
        ("/api/v1/itc", "total_turnover"),
        ("/api/v1/filing/gstr3b/late-fee", "previous_year_turnover"),
    ]

    @pytest.mark.parametrize("path, name", DECIMAL_QUERIES)
    @pytest.mark.parametrize("value", ["nan", "sNaN", "inf", "-inf", "1E+999999999", "-1"])
    def test_a_value_no_money_column_could_hold_is_refused(
        self, auth_client, paid_business, path, name, value
    ):
        response = auth_client.get(path, params={name: value, "is_nil": "false"})
        assert response.status_code == 422, (
            f"{path}?{name}={value} answered {response.status_code}"
        )

    @pytest.mark.parametrize("path, name", DECIMAL_QUERIES)
    def test_an_ordinary_amount_is_still_accepted(self, auth_client, paid_business, path, name):
        # The guard against over-correcting into refusing real money.
        response = auth_client.get(path, params={name: "150000", "is_nil": "false"})
        assert response.status_code == 200, response.text


class TestEveryStringInAUrlIsBounded:
    """A bare ``str`` in a URL accepts as much as the server will read.

    Unlike the integer and Decimal sweeps above, nothing here crashes. That is
    what made it the last one found: every route handles its oversized input
    perfectly well, and then *quotes it back*. The public GSTIN lookup echoed
    a 20KB path segment into a 20KB response body, and the filing routes put
    an unknown return type into a 404 detail. Reflection is the failure mode,
    not a 500, so it shows up in a bandwidth graph rather than an error log.

    Enums are absent by construction rather than by exception: a parameter
    typed ``InvoiceType`` or ``RiskLevel`` is not a ``str`` here, and a closed
    set needs no length. What this sweep catches is the parameter that is
    genuinely free text — a search term, a slug, an id in another system.

    A pattern counts as a bound. ``period`` carries the canonical ``YYYY-MM``
    regex, and the sweep in ``TestEveryPeriodParameterNamesARealMonth`` is what
    holds it to that; requiring a ``max_length`` on top would be noise.
    """

    def _string_params(self, route):
        found = []
        for param in (*route.dependant.query_params, *route.dependant.path_params):
            annotation = param.field_info.annotation
            options = [a for a in get_args(annotation) if a is not type(None)]
            if len(options) == 1:
                annotation = options[0]
            if annotation is str:
                found.append((param.name, param.field_info))
        return found

    def _is_bounded(self, field_info):
        for meta in getattr(field_info, "metadata", []) or []:
            if getattr(meta, "max_length", None) is not None:
                return True
            if getattr(meta, "pattern", None) is not None:
                return True
        return False

    def test_the_sweep_finds_the_parameters_it_is_checking(self):
        # A collector that finds nothing passes everything below. Named, not
        # counted: these are the free-text parameters a caller can send today.
        found = {
            name
            for route in collect_api_routes(app)
            if hasattr(route, "dependant")
            for name, _ in self._string_params(route)
        }
        assert {"search", "gstin", "return_type"} <= found, found

    def test_every_string_parameter_declares_a_length_or_a_pattern(self):
        offenders = []
        for route in collect_api_routes(app):
            if not hasattr(route, "dependant"):
                continue
            for name, field_info in self._string_params(route):
                if not self._is_bounded(field_info):
                    offenders.append(f"{route.path}:{name}")
        assert not offenders, (
            "these take a string of any length and every route here quotes its "
            "input back in an error — bound them with ``max_length``, or spell "
            f"a fixed-vocabulary segment ``app.core.params.Slug``: {offenders}"
        )

    def test_an_oversized_path_segment_is_refused_rather_than_echoed(self, auth_client):
        # The end-to-end half: a declared bound that FastAPI ignored would
        # still pass the metadata walk above.
        oversized = "A" * 20_000
        response = auth_client.get(f"/api/v1/filing/{oversized}/late-fee")
        assert response.status_code == 422
        assert len(response.content) < 2_000

    def test_a_real_return_type_still_answers_and_an_unknown_one_still_404s(
        self, auth_client
    ):
        # The guard against over-correcting: the bound must not disturb the
        # vocabulary the route owns, nor the 404 it answers outside it.
        assert auth_client.get("/api/v1/filing/gstr3b/late-fee").status_code == 200
        assert auth_client.get("/api/v1/filing/gstr2b/late-fee").status_code == 404


class TestEveryStringInARequestBodyIsBounded:
    """The same property as the URL sweep above, on the other input surface.

    A body field is the easier one to leave open, because most of them are
    already validated for *meaning* — a GSTIN is parsed and checksummed, a
    period is matched against a real month — and a field that cannot hold a
    wrong value reads as one that needs no length. It still runs whatever the
    caller sent through that validator, and the resulting 422 quotes it.

    The body-size middleware is a ceiling on all of this and not a substitute
    for it: it bounds the request, not the field, so it is satisfied by one
    field carrying the entire allowance.

    Nested models are walked, so a field added inside one is not exempt by
    being one level down.
    """

    def _models(self):
        """Every model the API accepts as a request body, nested ones included."""
        seen: dict[str, type] = {}
        pending = []
        for route in collect_api_routes(app):
            if not hasattr(route, "dependant"):
                continue
            for param in route.dependant.body_params:
                pending.append(param.field_info.annotation)
        while pending:
            annotation = pending.pop()
            for option in get_args(annotation) or ():
                pending.append(option)
            if not hasattr(annotation, "model_fields"):
                continue
            if annotation.__name__ in seen:
                continue
            seen[annotation.__name__] = annotation
            for field in annotation.model_fields.values():
                pending.append(field.annotation)
        return seen

    def _string_fields(self, model):
        for name, field in model.model_fields.items():
            annotation = field.annotation
            options = [a for a in get_args(annotation) if a is not type(None)]
            if len(options) == 1:
                annotation = options[0]
            if annotation is str:
                yield name, field

    def _is_bounded(self, field):
        for meta in getattr(field, "metadata", []) or []:
            if getattr(meta, "max_length", None) is not None:
                return True
            if getattr(meta, "pattern", None) is not None:
                return True
        return False

    def test_the_sweep_finds_the_models_it_is_checking(self):
        # A collector that finds nothing passes everything below.
        found = set(self._models())
        assert {"RegisterRequest", "InvoiceUpdate"} <= found, found

    def test_every_string_field_declares_a_length_or_a_pattern(self):
        offenders = []
        for name, model in self._models().items():
            for field_name, field in self._string_fields(model):
                if not self._is_bounded(field):
                    offenders.append(f"{name}.{field_name}")
        assert not offenders, (
            "these accept a string of any length. A validator that refuses the "
            "value is not a bound — it still runs on what was sent, and the 422 "
            f"quotes it: {offenders}"
        )

    def test_an_oversized_body_field_is_refused_rather_than_parsed(
        self, auth_client, sample_invoice_text
    ):
        # End to end, on the field that was the last one open. A declared bound
        # the model ignored would still pass the walk above.
        invoice_id = _upload(auth_client, sample_invoice_text)

        response = auth_client.patch(
            f"/api/v1/invoices/{invoice_id}",
            json={"counterparty_gstin": "2" * 20_000},
        )
        assert response.status_code == 422
        assert len(response.content) < 2_000

    def test_a_gstin_pasted_with_its_spacing_is_still_accepted(
        self, auth_client, sample_invoice_text
    ):
        # The guard against over-correcting: the bound is generous precisely so
        # the validator gets to give the better error, and so a real paste out
        # of a registration certificate still lands.
        invoice_id = _upload(auth_client, sample_invoice_text)

        response = auth_client.patch(
            f"/api/v1/invoices/{invoice_id}",
            json={"counterparty_gstin": "27 AAPFU0939F 1ZV"},
        )
        assert response.status_code == 200, response.text
        assert response.json()["counterparty_gstin"] == "27AAPFU0939F1ZV"


class TestTheWalkDescendsMoreThanOneLevel:
    """A router included into a router must not fall out of the sweep.

    Today every router in this app is included straight onto ``app``, so the
    walk in :mod:`app.core.routes` never recurses and the four sweeps that read
    it would pass just as well without the recursion. That is precisely the
    condition under which it breaks silently: grouping the routers under a
    single ``/api/v1`` router — the obvious next refactor, and the one FastAPI's
    own documentation shows — would move every route in the product one level
    down, and each of these sweeps would go on passing over an empty table.

    ``EXPECTED_PATHS`` catches that for the app as it is built today. These
    catch it for the shape the app has not been given yet.
    """

    def _nested_app(self):
        from fastapi import APIRouter, FastAPI

        leaf = APIRouter()

        @leaf.get("/leaf")
        def _leaf() -> dict:
            return {}

        middle = APIRouter(prefix="/middle")
        middle.include_router(leaf)
        outer = APIRouter(prefix="/outer")
        outer.include_router(middle)

        application = FastAPI()
        application.include_router(outer, prefix="/api")
        return application

    def test_a_route_three_routers_deep_is_still_collected(self):
        assert [route.path for route in collect_api_routes(self._nested_app())] == [
            "/api/outer/middle/leaf"
        ]

    def test_it_is_collected_once_and_not_once_per_level(self):
        """The lazy nodes carry their descendants' low-priority routes as well
        as their own, which is why the walk reads that list at the top and not
        inside the recursion. Getting it wrong duplicates every nested route
        per level of nesting, and a sweep asserting "no route does X" would
        then report the same offender three times."""
        paths = [route.path for route in collect_api_routes(self._nested_app())]
        assert len(paths) == len(set(paths))
